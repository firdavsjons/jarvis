"""Обрезанные фразы: «позвонить ма», «напиши себе в». Распознавание любого движка иногда теряет конец фразы.

Модель не спрашиваем: она догадалась бы за пользователя («позвонить маме»?) и сделала не то. Просим повторить.
Правило: фраза из двух слов и больше обрезана, если последнее слово — предлог, союз или частица (в, на, с, к, и…)
либо короче трёх букв и не из исключений. Исключения — местоимения, «да/нет/ок/ну», сокращения («тв», «вк»),
числа и слова подтверждения и управления.

Обрезанное начало (Этап 8.2.2): первое слово из 3–5 букв — не известное слово команды, а хвост такого слова
(«крой часы» ← закрой, «ключи свет» ← включи, «ставь таймер» ← поставь, «пиши маме» ← напиши, «правь» ← отправь).
Настоящие слова, совпадающие с хвостами («скажи», «делай», «читай», «помни», «будь», «иди»), не затрагиваются. В окне
диалога («да», «а завтра?», ответ на «кому?») это правило не применяется.
"""
import re

TRUNCATED_REPLY = "Фраза обрезана. Повторите, пожалуйста."

# Последнее слово такой фразы — не обрезок
NEVER_CUT = {"я", "ты", "мы", "вы", "он", "да", "нет", "ок", "ну", "тв", "вк",
             "стоп", "хватит", "отмена", "подтверждаю"}
# Предлоги, союзы и частицы: фраза не может на них заканчиваться
DANGLING = {"в", "во", "на", "с", "со", "к", "ко", "и", "а", "но", "о", "об", "у", "не", "ни", "по", "до", "за",
            "из", "от", "для", "при", "про", "над", "под", "без", "или", "чтобы"}
MIN_LAST_WORD = 3

# Слова, с которых начинаются команды и вопросы: если первое слово из них — начало не обрезано
COMMAND_VERBS = ("открой", "закрой", "включи", "выключи", "поставь", "напиши", "найди", "прочитай", "отправь", "покажи",
                 "сделай", "запомни", "забудь", "расскажи")
QUESTION_WORDS = ("какая", "какой", "сколько", "что", "где", "когда", "кто")
KNOWN_STARTS = {*COMMAND_VERBS, *QUESTION_WORDS}
# Настоящие слова, совпадающие с хвостами глаголов («скажи, сколько времени», «делай как знаешь»): обрезками не считаем
REAL_WORDS = {"скажи", "делай", "читай", "помни", "будь", "иди"}
TAIL_MIN, TAIL_MAX = 4, 5      # хвост глагола — 4–5 букв (первое слово фразы — 3–5 букв, 3-буквенные хвосты слишком шумные)


def _verb_tails():
    tails = set()
    for verb in COMMAND_VERBS:
        for i in range(1, len(verb)):
            if TAIL_MIN <= len(verb) - i <= TAIL_MAX:
                tails.add(verb[i:])
    return tails - KNOWN_STARTS - REAL_WORDS


VERB_TAILS = _verb_tails()


def is_truncated(text, in_window=False):
    """in_window — фраза принята потому, что открыто окно диалога (слова-активатора не было): обрезанное начало не ищем."""
    words = re.findall(r"\w+", str(text).lower().replace("ё", "е"))
    if len(words) < 2:
        return False
    if not in_window and 3 <= len(words[0]) <= 5 and words[0] in VERB_TAILS:
        return True
    last = words[-1]
    if last.isdigit() or last in NEVER_CUT:
        return False
    return last in DANGLING or len(last) < MIN_LAST_WORD
